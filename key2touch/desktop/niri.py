"""niri backend: IPC over $NIRI_SOCKET (no subprocess) and touch output config."""

import json
import os
import re
import socket
from pathlib import Path

from ..profile import CONFIG_DIR
from . import IPC_TIMEOUT, Backend

NIRI_DIR = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "niri"


def socket_path():
    path = os.environ.get("NIRI_SOCKET")
    if path and os.path.exists(path):
        return path
    # Stale env (niri restarted): find niri.<display>.<pid>.sock with a live pid.
    run = Path(os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}"))
    disp = os.environ.get("WAYLAND_DISPLAY", "wayland-1")
    for cand in sorted(run.glob(f"niri.{disp}.*.sock"), key=lambda p: -p.stat().st_mtime):
        pid = cand.name.rsplit(".", 2)[-2]
        if pid.isdigit() and os.path.exists(f"/proc/{pid}"):
            return str(cand)
    raise RuntimeError("找不到 niri IPC socket，需要在 niri 会话中运行")


def connect():
    path = socket_path()
    s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    s.settimeout(IPC_TIMEOUT)
    s.connect(path)
    return s


def request(req):
    with connect() as s:
        s.sendall((json.dumps(req) + "\n").encode())
        f = s.makefile("rb")
        reply = json.loads(f.readline())
    if "Err" in reply:
        raise RuntimeError(reply["Err"])
    return reply["Ok"]


def outputs():
    """name -> logical dict {x, y, width, height, scale, transform}; enabled outputs only."""
    res = request("Outputs")["Outputs"]
    return {n: o["logical"] for n, o in res.items() if o.get("logical")}


def focused_output():
    o = request("FocusedOutput").get("FocusedOutput")
    return o["name"] if o else None


def event_stream():
    """Returns a connected socket that streams JSON event lines."""
    s = connect()
    s.sendall(b'"EventStream"\n')
    return s


# ---- touch → output mapping -------------------------------------------------
#
# niri maps every libinput touch device to `input.touch.map-to-output`
# (or the first output if unset); there is no per-device mapping and no IPC
# for it.  So one include line in config.kdl is unavoidable, but the file it
# points to lives in key2touch's own config dir and is rewritten by key2touch.
# The include must come last (includes are positional); niri live-reloads.

INCLUDE_FILE = CONFIG_DIR / "niri-touch.kdl"
INCLUDE_LINE = f'include optional=true "{INCLUDE_FILE}"'
_INCLUDE_RE = re.compile(r'^\s*include\b.*"([^"]*)"')


def write_touch_output(name):
    content = (
        "// Generated by key2touch — maps the virtual touchscreen to the game output.\n"
        f'input {{\n    touch {{\n        map-to-output "{name}"\n    }}\n}}\n'
    )
    INCLUDE_FILE.parent.mkdir(parents=True, exist_ok=True)
    if INCLUDE_FILE.exists() and INCLUDE_FILE.read_text() == content:
        return
    INCLUDE_FILE.write_text(content)


def _our_include(lines):
    """Index of the last include line pointing at INCLUDE_FILE, or None."""
    found = None
    for i, line in enumerate(lines):
        m = _INCLUDE_RE.match(line)
        if m and Path(os.path.expanduser(m.group(1))) == INCLUDE_FILE:
            found = i
    return found


def include_status():
    """'ok' | 'missing' | 'not_last'"""
    try:
        lines = (NIRI_DIR / "config.kdl").read_text().splitlines()
    except OSError:
        return "missing"
    i = _our_include(lines)
    if i is None:
        return "missing"
    if re.search(r"^\s*(touch\s*\{|include\b)", "\n".join(lines[i + 1:]), re.M):
        return "not_last"
    return "ok"


def add_include(output):
    write_touch_output(output)
    # resolve(): config.kdl is often a symlink into a dotfiles repo; keep it one.
    cfg = (NIRI_DIR / "config.kdl").resolve()
    text = cfg.read_text()
    if not text.endswith("\n"):
        text += "\n"
    text += "\n// key2touch: virtual touchscreen output mapping (keep last)\n" + INCLUDE_LINE + "\n"
    tmp = cfg.with_name(cfg.name + ".key2touch-tmp")
    tmp.write_text(text)
    tmp.replace(cfg)  # atomic: niri never sees a half-written config


class NiriFocus:
    """Tracks the focused window's app_id from niri's event stream."""

    def __init__(self):
        self.sock = event_stream()
        self.buf = b""
        self.windows = {}  # id -> app_id
        self.focus_id = None
        self.window_id = None

    def fileno(self):
        return self.sock.fileno()

    def read(self):
        data = self.sock.recv(65536)
        if not data:
            raise EOFError("niri event stream closed")
        self.buf += data
        changed = False
        while b"\n" in self.buf:
            line, self.buf = self.buf.split(b"\n", 1)
            try:
                ev = json.loads(line)
            except ValueError:
                continue
            if "WindowsChanged" in ev:
                ws = ev["WindowsChanged"]["windows"]
                self.windows = {w["id"]: w.get("app_id") for w in ws}
                for w in ws:
                    if w.get("is_focused"):
                        self.focus_id = w["id"]
                changed = True
            elif "WindowOpenedOrChanged" in ev:
                w = ev["WindowOpenedOrChanged"]["window"]
                self.windows[w["id"]] = w.get("app_id")
                if w.get("is_focused"):
                    self.focus_id = w["id"]
                changed = True
            elif "WindowClosed" in ev:
                self.windows.pop(ev["WindowClosed"]["id"], None)
                changed = True
            elif "WindowFocusChanged" in ev:
                self.focus_id = ev["WindowFocusChanged"]["id"]
                changed = True
        self.window_id = self.focus_id
        return [self.windows.get(self.focus_id)] if changed else []


class NiriBackend(Backend):
    name = "niri"
    label = "niri"
    supports_focus = True

    @staticmethod
    def available():
        try:
            socket_path()
            return True
        except RuntimeError:
            return False

    def focus_source(self):
        return NiriFocus()

    def windows(self):
        try:
            ws_out = {w["id"]: w.get("output") for w in request("Workspaces")["Workspaces"]}
            return [{"app_id": w.get("app_id"), "title": w.get("title") or "",
                     "output": ws_out.get(w.get("workspace_id")), "focused": w.get("is_focused", False)}
                    for w in request("Windows")["Windows"]]
        except (OSError, RuntimeError, KeyError):
            return []

    def outputs(self):
        try:
            return {n: {"width": o["width"], "height": o["height"], "scale": o["scale"]}
                    for n, o in outputs().items()}
        except (OSError, RuntimeError, KeyError):
            return super().outputs()

    def focused_output(self):
        try:
            return focused_output()
        except (OSError, RuntimeError):
            return None

    def notice(self, output, n_outputs):
        st = include_status()
        if st == "missing":
            return "niri 需要在配置里加一行，触摸才能落到所选的显示器上", "设置"
        if st == "not_last":
            return "niri 配置里 key2touch 的 include 之后还有其他 include / touch 设置，触摸映射可能被覆盖", None
        return None

    def setup_text(self, output):
        return ("niri 只能通过自身配置指定触摸屏映射到哪个显示器，"
                "所以需要在 ~/.config/niri/config.kdl 末尾加这一行：\n\n"
                f"{INCLUDE_LINE}\n\n"
                "被引用的文件放在 ~/.config/key2touch/，切换显示器时由 key2touch 自动改写。")

    def setup(self, output):
        add_include(output)

    def touch_sync(self, output):
        if include_status() != "missing":
            write_touch_output(output)
